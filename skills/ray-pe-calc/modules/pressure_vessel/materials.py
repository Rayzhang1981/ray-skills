BASES = ("2024row1", "2024row2", "2011", "todo")


def basis_of(mat, basis=None):
    """取某材质的取值口径；未指定则用 default_basis。返回 (basis 名, row dict) 或 (None, None)。"""
    m = MATERIALS.get(mat)
    if not m:
        return None, None
    b = basis or m["default_basis"]
    row = m["rows"].get(b)
    if row is None:
        return None, None
    return b, row


def sigma_at(mat, T, basis=None):
    """取设计温度 T 下的许用应力。

    返回 (值, 是否已读原文) 或 (None, False)。
    ⚠️ 第二返回值语义：True = 该口径的数值已读**标准原文**；False = 未读原文（cross/todo）。
    """
    b, row = basis_of(mat, basis)
    if not row or not row["sig"]:
        return None, False
    ok = row["verify"] == "source"
    for tmax, s in row["sig"]:
        if T <= tmax:
            return s, ok
    return row["sig"][-1][1], ok


def check_limits(mat, T=None, P=None, dn=None, basis=None):
    """按材质使用限制检查。返回 (issues, warnings)，均为字符串列表。

    只判**能判的**：T/P/dn 为 None 时跳过该项（不猜）。
    """
    m = MATERIALS.get(mat)
    if not m:
        return ["未知材质 %r，只能按 --S 手填许用应力" % mat], []
    issues, warns = [], []
    b, row = basis_of(mat, basis)
    if row is None:
        issues.append("材质 %s 无口径 %r 的许用应力记录" % (mat, basis))
        return issues, warns
    if row["verify"] == "todo":
        issues.append("材质 %s 无『默认口径』的许用应力，工具拒绝估算 —— 可用 --basis "
                      "显式选择一个已收录口径（如 2024row1/2024row2），或用 --S 直接给定；"
                      "若各口径均为占位，则本材质确实未收录。" % mat)
    elif row["verify"] == "cross":
        warns.append("口径 %s 的许用应力仅部分经交叉验证（%s）" % (b, row["verify_note"]))
    if mat == "S30408" and b == "2011":
        warns.append("**当前为 2011 保守口径（既有设备/材质证明未取得）**；"
                     "若钢板可证明符合 GB/T 713.7-2023（Rp0.2≥230 MPa），"
                     "可用 --basis 2024row1 取提高值（≤100 ℃：137→153 MPa）。")
    if mat == "S31603" and b in ("2024row1", "2024row2"):
        warns.append("**本库未收录 S31603 的 2011 口径**；2024 提高值以钢板符合 "
                     "GB/T 713.7-2023（Rp0.2>=210 MPa）为前提。既有设备须先核材质证明 "
                     "与钢板标准（GB 24511 的 Rp0.2>=180 更低），否则不得直接用本值。")

    if mat == "S30408" and b == "2024row2":
        warns.append("**当前为 2024 表C.2 第二行（法兰/平盖类）**；"
                     "筒体/封头等允许微量永久变形之元件可用 --basis 2024row1（更高）。")
    if T is not None:
        if m["Tmin"] is not None and T < m["Tmin"]:
            issues.append("设计温度 %g ℃ **低于该材质的允许使用温度下限 %g ℃** -> 该材质不适用"
                          % (T, m["Tmin"]))
        if m["Tmax"] is not None and T > m["Tmax"]:
            issues.append("设计温度 %g ℃ 高于该材质的允许使用温度上限 %g ℃" % (T, m["Tmax"]))
        if row["sig"] and T > row["sig"][-1][0]:
            warns.append("设计温度 %g ℃ **超出表列最高温度档 %g ℃**，"
                         "本值仅为末档外推、不可作为设计依据" % (T, row["sig"][-1][0]))
    if P is not None and mat in ("Q235B", "Q235C") and P >= 1.6:
        issues.append("设计压力 %g MPa ≥ 1.6 MPa -> 超出 Q235 系列（附录D d 条）的适用范围" % P)
    if dn is not None and mat in ("Q235B", "Q235C") and dn > 16:
        warns.append("壳体名义厚度 %g mm > 16 mm -> 超出 Q235 系列用于壳体的厚度上限" % dn)
    if dn is not None and mat in ("Q235B", "Q235C") and dn < 6:
        warns.append("壳体名义厚度 %g mm < 6 mm -> 标准不要求冲击试验，即**无低温韧性验证**" % dn)
    return issues, warns


def describe(mat, basis=None):
    """供 --list-materials 输出单条材质摘要。"""
    m = MATERIALS.get(mat)
    if not m:
        return "未知材质：%s" % mat
    out = ["● %s" % m["full"], "    标准：%s" % m["std"]]
    for b in ("2024row1", "2024row2", "2011", "todo"):
        row = m["rows"].get(b)
        if row is None:
            continue
        mark = " <<默认" if b == m["default_basis"] else ""
        out.append("    [%s]%s %s" % (b, mark, row["label"]))
        out.append("        可信度：%s" % row["verify"])
        if row["sig"]:
            out.append("        [σ]t：" + " ｜ ".join("≤%g℃ %g" % (t, s) for t, s in row["sig"]))
        else:
            out.append("        [σ]t：**未收录**（须用 --S 手填）")
        out.append("        出处：%s" % row["verify_note"])
    out.append("    C1=%.2f mm ｜ C2=%.2f mm" % (m["C1"], m["C2"]))
    if m["Tmin"] is not None or m["Tmax"] is not None:
        out.append("    允许使用温度：%s ~ %s ℃"
                   % ("—" if m["Tmin"] is None else "%g" % m["Tmin"],
                      "—" if m["Tmax"] is None else "%g" % m["Tmax"]))
    for code, txt, sub in m["limits"]:
        out.append("    限制%s %s%s" % ("（%s）" % code if code else "", txt,
                                      ("　→ %s" % sub) if sub else ""))
    if m.get("note"):
        out.append("    备注：%s" % m["note"])
    return "\n".join(out)
